-- Run after the project access migration. Synthetic rows and claims are rolled back.
begin;
create temporary table security_test_results(test text,passed boolean);
grant all on security_test_results to authenticated;
create temporary table qa_ids(owner_a uuid,owner_b uuid,project_a uuid,project_b uuid);
insert into qa_ids values(gen_random_uuid(),gen_random_uuid(),gen_random_uuid(),gen_random_uuid());
grant select on qa_ids to authenticated;
insert into auth.users(id,aud,role,email) select owner_a,'authenticated','authenticated','security-a-'||owner_a||'@example.invalid' from qa_ids union all select owner_b,'authenticated','authenticated','security-b-'||owner_b||'@example.invalid' from qa_ids;
insert into public.projects(id,slug,package_type,owner_user_id,payment_status,project_status) select project_a,'security-qa-'||project_a,'signature',owner_a,'paid','active' from qa_ids union all select project_b,'security-qa-'||project_b,'signature',owner_b,'paid','active' from qa_ids;
insert into public.website_content(project_id,welcome_text) select project_a,'Owner A' from qa_ids union all select project_b,'Owner B' from qa_ids;
insert into public.schedule_items(project_id,item_time,item_title,sort_order) select project_a,'15:00'::time,'A',1 from qa_ids union all select project_b,'15:00'::time,'B',1 from qa_ids;
insert into public.rsvp_responses(project_id,guest_name,attending,adults_count,children_count,people) select project_a,'Synthetic A','yes',1,0,'[]'::jsonb from qa_ids union all select project_b,'Synthetic B','yes',1,0,'[]'::jsonb from qa_ids;
insert into security_test_results select 'anonymous project SELECT denied',not has_table_privilege('anon','public.projects','SELECT');
insert into security_test_results select 'anonymous project TRUNCATE denied',not has_table_privilege('anon','public.projects','TRUNCATE');
insert into security_test_results select 'anonymous direct RSVP INSERT denied',not has_table_privilege('anon','public.rsvp_responses','INSERT');
select set_config('request.jwt.claim.sub',(select owner_a::text from qa_ids),true);
set local role authenticated;
do $$
declare a uuid; b uuid; n integer; denied boolean;
begin
 select project_a,project_b into a,b from qa_ids;
 insert into security_test_results select 'owner reads own project',count(*)=1 from public.projects where id=a;
 insert into security_test_results select 'owner cannot read another project',count(*)=0 from public.projects where id=b;
 update public.projects set couple_display_name='Edited A' where id=a;
 get diagnostics n=row_count;
 insert into security_test_results values('owner can edit public project fields',n=1);
 update public.projects set couple_display_name='Forbidden' where id=b;
 get diagnostics n=row_count;
 insert into security_test_results values('owner cannot edit another project',n=0);
 denied:=false;
 begin update public.projects set package_type='atelier' where id=a; exception when insufficient_privilege then denied:=true; end;
 insert into security_test_results values('owner cannot upgrade package directly',denied);
 denied:=false;
 begin update public.projects set owner_user_id=(select owner_a from qa_ids) where id=b; exception when insufficient_privilege then denied:=true; end;
 insert into security_test_results values('owner cannot reassign ownership',denied);
 denied:=false;
 begin update public.projects set payment_status='paid' where id=a; exception when insufficient_privilege then denied:=true; end;
 insert into security_test_results values('owner cannot change payment state',denied);
 insert into security_test_results select 'owner sees only own content',count(*)=1 from public.website_content where project_id in(a,b);
 update public.website_content set welcome_text='Edited' where project_id=a;
 get diagnostics n=row_count;
 insert into security_test_results values('owner edits own content',n=1);
 update public.website_content set welcome_text='Forbidden' where project_id=b;
 get diagnostics n=row_count;
 insert into security_test_results values('owner cannot edit foreign content',n=0);
 denied:=false;
 begin insert into public.schedule_items(project_id,item_title,sort_order) values(b,'Forbidden',2); exception when insufficient_privilege then denied:=true; end;
 insert into security_test_results values('owner cannot insert foreign schedule',denied);
 delete from public.schedule_items where project_id=b;
 get diagnostics n=row_count;
 insert into security_test_results values('owner cannot delete foreign schedule',n=0);
 delete from public.schedule_items where project_id=a;
 insert into public.schedule_items(project_id,item_title,sort_order) values(a,'Replacement',1);
 insert into security_test_results select 'editor can replace own schedule',count(*)=1 from public.schedule_items where project_id=a;
 update public.projects set accommodation_reminder_days=2 where id=a;
 get diagnostics n=row_count;
 insert into security_test_results values('owner reminder settings remain editable',n=1);

 insert into security_test_results select 'owner sees only own guest responses',count(*)=1 from public.rsvp_responses where project_id in(a,b);
 update public.rsvp_responses set accommodation_room='101' where project_id=a;
 get diagnostics n=row_count;
 insert into security_test_results values('owner accommodation assignment works',n=1);
 update public.rsvp_responses set accommodation_room='Forbidden' where project_id=b;
 get diagnostics n=row_count;
 insert into security_test_results values('foreign accommodation assignment denied',n=0);
 denied:=false;
 begin insert into public.rsvp_responses(project_id,guest_name,attending) values(a,'Forbidden','no'); exception when insufficient_privilege then denied:=true; end;
 insert into security_test_results values('direct client RSVP submission denied',denied);
end $$;
reset role;
select set_config('request.jwt.claim.sub',(select owner_b::text from qa_ids),true);
set local role authenticated;
insert into security_test_results select 'second owner reads own project',count(*)=1 from public.projects where id=(select project_b from qa_ids);
insert into security_test_results select 'second owner cannot read first owner',count(*)=0 from public.projects where id=(select project_a from qa_ids);
reset role;
select * from security_test_results;
rollback;
